SECOND_OF = {'如果': '就', '假如': '就', '要是': '就', '只有': '才', '唯有': '才', '除非': '才', '不但': None, '不仅': '还',
             '虽然': None, '尽管': '还是', '无论': '都', '不管': '都', '因为': None, '由于': '因此'}


def second_word(stem, a):
    for w in ['而且', '甚至', '还是', '但是', '所以', '因此', '还', '就', '才', '都']:
        if w in stem.split('___', 1)[1]:
            return w
    return SECOND_OF.get(a)


def fix_guanlian(key):
    cls_ans, rel, pool, stems = B[key]
    name, d, fn = load_bank(key)
    n = 0
    seen_cls = {}
    for i, q in enumerate(d['questions']):
        if not q['q'].startswith('选关联词填入') or q['类'] not in cls_ans:
            continue
        # 已改过的题：单空且选项为单词
        k = seen_cls.get(q['类'], 0); seen_cls[q['类']] = k + 1
        a = cls_ans[q['类']]
        st_list = stems.get(q['类']) or stems[None]
        stem = st_list[k % len(st_list)]
        rng = random.Random('%s|%d' % (key, i))
        combo = (k // len(st_list)) % len(pool)
        dis = [w for j, w in enumerate(pool) if j != combo][:3]
        opts = dis + [a]
        rng.shuffle(opts)
        filled = stem.replace('___', a)
        if key == 'xian_ranhou':
            exp = '前面有「先」，后面用「%s」，按%s说两件事：%s' % (a, rel, filled) + \
                  '其他几个词不合：' + '，'.join('「%s」%s' % (w, SECOND_MEAN[w]) for w in dis) + '，都不是先后顺序。'
        else:
            sw = second_word(stem, a)
            exp = '后面用了「%s」，前面填「%s」，表示%s：%s' % (sw, a, rel, filled) + \
                  '其他几个词配不上「%s」：' % sw + '，'.join('「%s」要配「%s」' % (w, PAIR[w]) for w in dis) + '。'
        nq = {'q': '选关联词填入___处：' + stem, 'options': opts, 'answer': opts.index(a), '解析': exp, '类': q['类']}
        if q != nq:
            d['questions'][i] = nq; n += 1
    save_bank(fn, name, d)
    return n


