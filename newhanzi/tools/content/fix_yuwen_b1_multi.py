def fix_fanwen():
    name, d, fn = load_bank('fanwen')
    n = 0; miss = []
    for i, q in enumerate(d['questions']):
        if not q['q'].startswith('选词填入') or q['类'] not in ('肯定式反问', '否定式反问'):
            continue
        new = dict(q)
        stem = q['q'].split('：')[-1]
        if stem == '难道他___神仙吗？':  # 「难道他不是神仙吗」意思是「他是神仙」，不合常理
            stem = '难道他___你的好朋友吗？'
            new['options'] = ['没' if o == '是仙' else o for o in q['options']]
        a = new['options'][new['answer']]
        m = MEAN.get((q['类'], stem, a))
        if not m:
            miss.append((i, stem, a)); continue
        new['q'] = '选词填入___处（要表达的意思是：%s）：%s' % (m, stem)
        filled = stem.replace('___', a)
        if q['类'] == '肯定式反问':
            new['解析'] = '「%s」用肯定的说法，表达否定的意思：%s。反问句的意思和字面相反。' % (filled, m)
        else:
            new['解析'] = '「%s」用否定的说法，表达肯定的意思：%s。反问句的意思和字面相反。' % (filled, m)
        if new != q: d['questions'][i] = new; n += 1
    save_bank(fn, name, d)
    return n, miss


def fix_wulun_yiwenci():
    name, d, fn = load_bank('wulun_dou')
    n = 0
    for i, q in enumerate(d['questions']):
        if q['类'] != '无论+疑问词式' or not q['q'].startswith('选关联词填入') or q['q'].count('___') != 2:
            continue
        a = q['options'][q['answer']]
        rest = a.split('都', 1)
        new = dict(q); opts = list(q['options'])
        for j, o in enumerate(opts):
            if j != q['answer'] and o.startswith(rest[0]) and o[len(rest[0]):].startswith('也'):
                for alt in ['但是', '而且', '才', '就']:
                    cand = rest[0] + alt + rest[1]
                    if cand not in opts: opts[j] = cand; break
        new['options'] = opts
        if new != q: d['questions'][i] = new; n += 1
    save_bank(fn, name, d)
    return n


