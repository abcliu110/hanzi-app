def fix_lzg():
    name, d, fn = load_bank('le_zhe_guo')
    n = 0; cnt = {}
    for i, q in enumerate(d['questions']):
        if '( )' not in q['q'] or q['类'] not in LZG or not q['q'].startswith('下面句子括号里填哪个词正确'):
            continue
        k = cnt.get(q['类'], 0); cnt[q['类']] = k + 1
        stems, opts0, tpl = LZG[q['类']]
        s = stems[k % len(stems)]
        opts = list(opts0); random.Random('lzg|%d' % i).shuffle(opts)
        a = opts0[0]
        nq = {'q': '下面句子括号里填哪个词正确？\n' + s, 'options': opts, 'answer': opts.index(a),
              '解析': tpl.format(s=s.replace('( )', a)), '类': q['类']}
        if q != nq: d['questions'][i] = nq; n += 1
    save_bank(fn, name, d)
    return n


