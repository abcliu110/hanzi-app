def fix_biyu():
    name, d, fn = load_bank('biyu')
    n = 0
    tip = {'明喻': '组成明喻', '暗喻': '组成暗喻', '借喻': '组成借喻'}
    for i, q in enumerate(d['questions']):
        if not q['q'].startswith('选词填入') or q['类'] not in tip:
            continue
        stem = q['q'].split('：', 1)[1]
        new = dict(q)
        if stem == '___红着脸笑了。':
            # 「苹果红着脸笑了」是拟人，不是借喻
            stem = '___走进了教室。'
            opts = ['一群花朵', '一群学生', '一群孩子', '几位老师']
            random.Random('biyu|%d' % i).shuffle(opts)
            new['options'] = opts; new['answer'] = opts.index('一群花朵')
        a = new['options'][new['answer']]
        new['q'] = '选词填入___处，%s：%s' % (tip[q['类']], stem)
        filled = stem.replace('___', a)
        if q['类'] == '明喻':
            other = ''.join('「%s」' % o for o in new['options'] if o not in ('像', '是'))
            new['解析'] = '「%s」用「像」把两样东西连起来打比方，本体和喻体都出现，是明喻。' % filled + ('用「是」就成了暗喻；' if '是' in new['options'] else '') + other + '都不是打比方。'
        elif q['类'] == '暗喻':
            other = ''.join('「%s」' % o for o in new['options'] if o not in ('像', '是'))
            new['解析'] = '「%s」用「是」直接把本体说成喻体，是暗喻。' % filled + ('用「像」就成了明喻；' if '像' in new['options'] else '') + other + '都不是打比方。'
        else:
            new['解析'] = '「%s」只出现喻体「%s」，不出现本体，是借喻。填其他词就是平常的叙述，没有打比方。' % (filled, a)
        if new != q: d['questions'][i] = new; n += 1
    save_bank(fn, name, d)
    return n


