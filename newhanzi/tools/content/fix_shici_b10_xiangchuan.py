#!/usr/bin/env python3
"""F3 批次10（G 组）：把传说写成事实的地方加「相传」，不把话塞给作者（报告 §11 末段）。幂等。
- famous《赠汪伦》「十里桃花、万家酒店」：出自清代袁枚《随园诗话》补遗一类笔记的传说 → 加「相传」；
- famous《夏日绝句》story「连我一个女子都不如，真该惭愧！」是替作者编的话 → 改成「借项羽宁死不肯过江东，讽刺只顾逃跑的南宋君臣」；
- choice「李煜写下《虞美人》后，宋太宗是什么反应？」：出自宋人笔记（王铚《默记》）的记载 → 题干与解析加「相传」；
- choice「野火烧不尽」解析「白居易16岁写下这两句一举成名」：出自唐张固《幽闲鼓吹》等笔记（顾况赏识的故事）→ 改为「相传……得到前辈顾况的赏识」；
- judge「端午节是为了纪念屈原」=对：端午起源有多种说法 → 题干改「民间流传最广的说法是：端午节赛龙舟、吃粽子是为了纪念屈原」=对，解析注明还有其他说法。
"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fix_shici_io as io
s = io.load('shici'); q = io.load('quiz'); M = q['modes']; n = 0
for f in s['famous']:
    if f['title'] == '赠汪伦' and f['story'].startswith('汪伦用'):
        f['story'] = '相传' + f['story']; n += 1
    if f['title'] == '夏日绝句' and '连我一个女子都不如' in f['story']:
        f['story'] = '南宋朝廷丢了北方、逃到江南。李清照借项羽兵败后宁死也不肯过江东逃生的气节，讽刺只顾逃跑的南宋君臣。'; n += 1
for x in M['choice']:
    if x['q'] == '李煜写下《虞美人》后，宋太宗是什么反应？':
        x['q'] = '相传李煜写下《虞美人》后，宋太宗是什么反应？'
        x['exp'] = '相传李煜写了“问君能有几多愁”，宋太宗听说后很不高兴（见宋人笔记《默记》）。不久，李煜去世，年仅42岁。'; n += 1
    if '白居易16岁写下这两句一举成名' in x.get('exp', ''):
        x['exp'] = x['exp'].replace('白居易16岁写下这两句一举成名', '相传白居易少年时带着这首诗去拜见前辈顾况，因此得到赏识'); n += 1
for x in M['judge']:
    if x['q'] == '端午节是为了纪念屈原。':
        x['q'] = '民间流传最广的说法是：端午节赛龙舟、吃粽子是为了纪念屈原。'
        x['exp'] = '对。这是流传最广的说法；端午节的来历还有别的说法（如纪念伍子胥、驱邪避疫）。'; n += 1
io.dump('shici', s); io.dump('quiz', q)
print('改', n, '处')
