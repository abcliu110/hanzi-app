#!/usr/bin/env python3
"""F1 语法 4f：排比库「短语排比」例句（报告 §6）。幂等。
原短语排比例句多是普通并列（「苹果、香蕉、梨子都是水果」「老师、同学、家长都来了」），还有错字「红的、黄的、紫的的花」。
统编教材讲排比：三项或三项以上、结构相同或相似、意思相关、语气一致，用来增强语势。普通名词罗列不是排比。
→ 换成真正的短语排比句（成串的结构相同的短语，有加强语势的作用），C 填空题按「结构相同」设干扰项重写，D 说法题去掉旧例句。
"""
import os, sys, random, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fix_yuwen_io import load_bank, save_bank

NEW = [  # (句子, 填空题干, 正确, 干扰1, 干扰2, 干扰3)
    ('我们要做有理想、有道德、有文化、有纪律的人。', '我们要做有理想、有道德、___、有纪律的人。', '有文化', '文化', '没有文化', '有理想'),
    ('读书能开阔眼界、增长知识、陶冶情操。', '读书能开阔眼界、___、陶冶情操。', '增长知识', '知识', '知识增长', '开阔眼界'),
    ('这是一个充满希望、充满活力、充满欢笑的地方。', '这是一个充满希望、___、充满欢笑的地方。', '充满活力', '活力', '很有活力的', '充满希望'),
    ('同学们个个精神饱满、斗志昂扬、信心十足。', '同学们个个精神饱满、___、信心十足。', '斗志昂扬', '斗志', '昂扬的斗志', '精神饱满'),
    ('他用勤劳的双手、聪明的头脑、坚强的意志改变了家乡。', '他用勤劳的双手、___、坚强的意志改变了家乡。', '聪明的头脑', '头脑', '头脑聪明', '勤劳的双手'),
    ('校园里到处是鲜艳的花朵、嫩绿的小草、欢快的笑声。', '校园里到处是鲜艳的花朵、___、欢快的笑声。', '嫩绿的小草', '小草', '小草嫩绿', '鲜艳的花朵'),
    ('老师用爱心、耐心、细心照顾着每一个孩子。', '老师用爱心、___、细心照顾着每一个孩子。', '耐心', '很耐心地', '耐心的老师', '爱心'),
    ('妈妈的话像春风一样温暖、像泉水一样清甜、像阳光一样明亮。', '妈妈的话像春风一样温暖、___、像阳光一样明亮。', '像泉水一样清甜', '泉水', '清甜的泉水', '像春风一样温暖'),
]
OLD = ['红的、黄的、紫的的花。', '高高的山、清清的水、蓝蓝的天。', '唱歌、跳舞、画画是我的爱好。', '苹果、香蕉、梨子都是水果。',
       '大大的眼睛、长长的头发、小小的鼻子。', '跑步、跳绳、游泳都是运动。', '红红的、黄黄的、绿绿的叶子。', '老师、同学、家长都来了。',
       '红红的太阳、蓝蓝的天、白白的云。', '读书、写字、画画、唱歌样样都好。', '大大的西瓜、甜甜的葡萄、红红的苹果。',
       '春天、夏天、秋天、冬天各有各的美。', '高兴、快乐、幸福、满足写在脸上。', '钢笔、铅笔、橡皮、尺子摆在桌上。', '青青的草、红红的花、绿绿的叶。']
MAP = {o: NEW[i % len(NEW)][0] for i, o in enumerate(OLD)}
ST_T = ['短语排比是把三个或三个以上结构相同、意思相关的短语排在一起，增强语势。', '「%s」用了短语排比。', '短语排比的几个短语结构相同、语气一致。']
ST_F = ['「苹果、香蕉、梨子都是水果」是短语排比。', '短语排比用完整的句子。', '短语排比只要两个短语就够了。', '「月亮像玉盘」是短语排比。', '短语排比表示比喻。', '「春天来了，花开了，草绿了」是短语排比。']


def main():
    name, d, fn = load_bank('paibi')
    n = 0; kc = kd = 0
    for i, q in enumerate(d['questions']):
        old = json.dumps(q, ensure_ascii=False)
        s = old
        for a, b in MAP.items():
            s = s.replace(a.rstrip('。'), b.rstrip('。'))
        q2 = json.loads(s)
        q2['options'] = [o.replace('。。', '。') for o in q2['options']]
        q2['q'] = q2['q'].replace('。。', '。'); q2['解析'] = q2['解析'].replace('。。', '。')
        rng = random.Random('pb|%d' % i)
        if q2['类'] == '短语排比' and q2['q'].startswith('选词填入'):
            s0, stem, a, b1, b2, b3 = NEW[kc % len(NEW)]; kc += 1
            opts = [a, b1, b2, b3]; rng.shuffle(opts)
            q2.update({'q': '选词填入___处：%s' % stem, 'options': opts, 'answer': opts.index(a),
                       '解析': '前后都是结构相同的短语，填「%s」才和它们结构一致、意思不重复，组成短语排比。「%s」「%s」结构对不上，「%s」和前面重复了。' % (a, b1, b2, b3)})
        if q2['类'] == '短语排比' and q2['q'].startswith('下面说法正确'):
            t = ST_T[kd % 3]
            if '%s' in t: t = t % NEW[kd % len(NEW)][0].rstrip('。')
            f = ST_F[:]; random.Random('pbD|%d' % kd).shuffle(f); kd += 1
            opts = [t] + f[:3]; rng.shuffle(opts)
            q2.update({'options': opts, 'answer': opts.index(t), '解析': t + ' 其他三项都不对：' + '；'.join(x.rstrip('。') for x in f[:3]) + '。普通的名词罗列（如「苹果、香蕉、梨子」）不是排比。'})
        assert len(set(q2['options'])) == len(q2['options']), q2
        if q2 != q:
            d['questions'][i] = q2; n += 1
    save_bank(fn, name, d)
    return n


if __name__ == '__main__':
    print('paibi', main())
