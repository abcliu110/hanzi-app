def run():
    B = set(L.chars_b()); n = 0
    for z, (t, cj) in T.items():
        assert z in B, z
        d = L.load(z); dm = d['dim']
        dm['字源']['讲解'] = t
        if cj:
            xs = dm.setdefault('形声拆解', {}); xs['meaning'], xs['sound'] = cj; xs.setdefault('note', '')
        if L.save(z, d): n += 1; print('改', z)
