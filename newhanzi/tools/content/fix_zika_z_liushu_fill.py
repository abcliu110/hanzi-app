def kind(jj):
    m = re.match(r'^(?:.是)?(象形|指事|会意|形声)', jj)
    if not m: return None
    t = m.group(1)
    if t == '会意' and re.match(r'^(?:.是)?会意兼形声', jj): t = '形声'
    return t + '字'

