"""zika-b（第 1751–3500 字）：六书 chip 与讲解矛盾、算法推断形声的声旁/形旁/依据、编造《说文》引文。
人工逐字，口径：以汉典「字形分析」为准，与《说文》不同时在讲解或依据里写明。可重复运行。
依据见 docs/xiufu/shencha-2026-11-05/fix-zika-b.md。"""
