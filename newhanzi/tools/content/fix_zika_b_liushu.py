def ls_set(dm, value=..., sheng=..., xing=..., yiju=...):
    l6 = dm.setdefault('六书', {})
    for k, v in (('value', value), ('声旁', sheng), ('形旁', xing), ('依据', yiju)):
        if v is ...: continue
        if v is None: l6.pop(k, None)
        else: l6[k] = v


def jj(dm, t): dm['字源']['讲解'] = t


def chai(dm, meaning=None, sound=None, note=None):
    xs = dm.setdefault('形声拆解', {})
    for k, v in (('meaning', meaning), ('sound', sound), ('note', note)):
        if v is not None: xs[k] = v


E = {}
def fix(z):
    def deco(f): E[z] = f; return f
    return deco


# —— 讲解与 chip 矛盾 ——
@fix('墨')   # 汉典：会意兼形声；chip 形声 → 讲解首句与 chip 对齐（同 zika-a 两/政 处理）
def _(dm):
    dm['字源']['讲解'] = dm['字源']['讲解'].replace('墨是会意兼形声字', '墨是形声字（也兼会意）', 1)

@fix('整')   # 汉典：会意兼形声（从攵、从束、从正声）
def _(dm):
    t = dm['字源']['讲解']
    if t.startswith('会意兼形声字。'): jj(dm, '形声字（也兼会意）。' + t[len('会意兼形声字。'):])
    chai(dm, meaning='攵（敲打）＋束（约束）：管束使它整齐', sound='正：表示读音，也有“端正”的意思')

@fix('绞')   # 汉典字形分析：形声，从纟、交声；《说文》“从交从糸”
def _(dm):
    t = dm['字源']['讲解']
    if t.startswith('会意兼形声字。'): jj(dm, '形声字（也兼会意）。' + t[len('会意兼形声字。'):])
    ls_set(dm, yiju='汉典字形分析：从纟、交声；《说文》作“从交从糸”，“交”也表示意思')

@fix('彭')   # 原讲解为汉典倾倒且自称会意；《说文》“鼓聲也。从壴彡聲”，chip 形声 → 按《说文》重写
def _(dm):
    jj(dm, '形声字。《说文》说“彭，鼓声也。从壴，彡声”。左边的“壴”像一面鼓，本义是咚咚的鼓声。'
           '今天常用作姓，如“彭德怀”；也用在地名里，如“彭城”（今江苏徐州一带）。（来源：汉典；《说文解字》）')

@fix('得')   # 原讲解 1410 字汉典倾倒（含“得其尸于井”、dǎi 音）；chip 形声与《说文》一致，讲解写明古字形
def _(dm):
    jj(dm, '古文字的“得”像一只手拿着“贝”（古代的钱），表示得到财物，后来又加上和走路有关的“彳”。'
           '《说文》说“得，行有所得也”，把它分析为形声字（从彳，㝵声）。本义是得到、获得，如“得奖”“心得”；'
           '读 de 时用在动词后面，如“跑得快”；读 děi 时表示必须，如“我得走了”。（来源：汉典；《说文解字》）')

@fix('拿')   # chip 会意，汉典：会意，从合、从手；原讲解自称形声、说右边有“奴”、并编造《说文》“拿，持也”
def _(dm):
    jj(dm, '会意字。上面是“合”，下面是“手”，手合拢起来就是拿住、握住。《说文》里没有“拿”字，只收了它的异体“拏”。'
           '常用义是用手握住或取，如“拿笔”“拿东西”；引申为掌握，如“拿主意”“拿手好戏”。（来源：汉典）')

# —— 编造《说文》引文（《说文》无此字头，卡内也无说文条） ——
@fix('捧')   # 汉典：形声，从手，奉声；本义两手承托，古多作“奉”
def _(dm):
    jj(dm, '形声字。左边“扌”表示和手有关，右边“奉”提示读音，古书里这个意思多写作“奉”。'
           '本义是两只手托着，如“捧着书”“捧起一捧水”；引申为吹嘘、抬举，如“捧场”“吹捧”。（来源：汉典）')

@fix('揉')   # 汉典：形声，从手，柔声；本义使木弯曲或伸直
def _(dm):
    jj(dm, '形声字。左边“扌”表示用手，右边“柔”提示读音，也有“柔软”的意思。'
           '古时指把木头弄弯或弄直；今天常用义是用手反复地搓、按，如“揉面”“揉眼睛”。（来源：汉典）')

# —— 算法推断形声、《说文》为会意（逐字核汉典字形分析，均作形声 → 保留 chip，换掉算法“依据”，修正部件） ——
YJ = {
    '噪': ('喿', '口', '汉典字形分析：从口、喿声；《说文》作“从品在木上”（群鸟在树上叫）'),
    '帽': ('冒', '巾', '汉典字形分析：从巾、冒声；“冒”本来就像帽子，也表示意思'),
    '愚': ('禺', '心', '汉典字形分析：从心、禺声；《说文》作“从心从禺”'),
    '挚': ('执', '手', '汉典字形分析：从手、执声；《说文》作“从手从執”'),
    '殷': ('㐆', '殳', '汉典字形分析：右形左声；《说文》作“从㐆从殳”'),
    '置': ('直', '罒', '汉典字形分析：从网（罒）、直声；《说文》作“从网、直”'),
    '致': ('至', '攵', '汉典字形分析：从攵、至声；《说文》作“从夊从至”'),
    '貌': ('皃', '豸', '汉典：从豹省，皃声；“皃”像人脸，也表示意思'),
    '躬': ('弓', '身', '汉典字形分析：从身、弓声；《说文》字头作“躳”（从身从呂）'),
}
for _z, (_s, _x, _y) in YJ.items():
    E[_z] = (lambda s, x, y: lambda dm: ls_set(dm, value='形声字', sheng=s, xing=x, yiju=y))(_s, _x, _y)

@fix('垒')   # 汉典：原为形声（壘，从土，畾声）；简化后上部写成三个“厶”，算法把“厽”当声旁不对
def _(dm):
    ls_set(dm, value='形声字', sheng='畾（繁体“壘”的上部）', xing='土',
           yiju='汉典：原为形声字（壘，从土，畾声）；简化后上部写成三个“厶”，看不出读音了')

_E2 = dict(E)
@fix('殷')
def _(dm):
    _E2['殷'](dm)
    chai(dm, meaning='殳：手拿器具', sound='㐆：表示读音（汉典字形分析）')

_E3 = dict(E)
@fix('致')
def _(dm):
    _E3['致'](dm)
    chai(dm, meaning='攵（原是“夊”，走路的脚）', sound='至：表示读音，也有“到达”的意思', note='')

_E4 = dict(E)
@fix('貌')
def _(dm):
    _E4['貌'](dm)
    chai(dm, meaning='豸（原是“豹”省写）', sound='皃：mào，表示读音，像人脸，也表示意思')


def run():
    B = set(L.chars_b()); n = 0
    for z, f in E.items():
        assert z in B, z
        d = L.load(z); f(d['dim'])
        if z in YJ or z in ('垒', '绞'): d['src']['六书'] = '人工核对（汉典字形分析）'
        if L.save(z, d): n += 1; print('改', z)
    print('改动', n, '字')

if __name__ == '__main__': run()
