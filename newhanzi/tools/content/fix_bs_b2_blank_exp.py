Q, fmt = load(QBUSHOU)
M = Q['modes']
n = 0
import re
for q in M['blank']:
    m = re.search(r"变成'(.)'", q['s'])
    z = m.group(1) if m else None
    if z == '时' and '寺' in q['opts']:
        q['opts'][q['opts'].index('寺')] = '寸'; n += 1
    if z in E and q['exp'] != E[z]:
        assert q['opts'][q['a']] == E[z][1], (z, q['opts'][q['a']])
        q['exp'] = E[z]; n += 1
for q in M['choice']:
    if q['q'] == "'时'的部首是？" and q['exp'].startswith('时=日+寺'):
        q['exp'] = '时=日+寸（繁体写作「時」，是日+寺），是日部的字，和时间有关。'
        for t in q.get('误解标注') or []:
            if t['选项文本'] == '人':
                t['误解'] = '没看清字形：时由日和寸组成，里面没有「人」'
            elif t['选项文本'] == '寺':
                t['误解'] = '把繁体「時」右边的声旁「寺」当部首（简化字时的右边是「寸」）'
            elif t['选项文本'] == '寸':
                t['误解'] = '把右边的「寸」当部首；寸是繁体「時」里的声旁「寺」简化来的，表义的是「日」'
        n += 1
for q in M['rewrite']:
    if q['from'] == "'时'（日+寺）":
        q['from'] = "'寺'"; q['target'] = "给'寺'加上'扌'"
        q['exp'] = '寺是声旁：扌+寺=持（坚持）；诗、特也用寺作声旁。'; n += 1
left = sum('形声字小窍门' in q['exp'] for q in M['blank'])
assert left == 0, left
save(QBUSHOU, Q, fmt)
print('改', n, '处；blank 模板句剩', left)
