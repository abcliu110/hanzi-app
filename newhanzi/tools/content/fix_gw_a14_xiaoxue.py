def js_str(s):
    assert "'" not in s and '\\' not in s and '\n' not in s, s
    return "'" + s + "'"

def entry_js(d):
    w = W[d['title']]
    yw = re.sub(r'\(——[^)]*\)\s*$', '', w['text']).strip()
    # 逐句译意与原文句数一致（按 。！？ 及其后的引号断句）
    sens = [x for x in re.findall(r'[^。！？]+[。！？][”’]*', yw)]
    assert ''.join(sens) == yw and len(sens) == len(d['句今']), (d['title'], len(sens), len(d['句今']))
    for z, g in d['重点']:
        assert z in yw, (d['title'], z)
    assert w['ce'] == d['ce'], d['title']
    yy = ''.join(d['句今'])
    zd = ','.join('[%s,%s]' % (js_str(z), js_str(g)) for z, g in d['重点'])
    cc = ','.join(js_str(u) for u in d['出处'])
    return ("{title:%s, ke:'小学课内', ce:%s, ceBasis:%s, author:%s, source:%s, cat:%s,\n原文:%s,\n导读:%s,\n译意:%s,\n重点:[%s],\n出处:[%s]}"
            % (js_str(d['title']), js_str(d['ce']), js_str(d['ceBasis']), js_str(d['author']), js_str(d['source']), js_str(d['cat']),
               js_str(yw), js_str(d['导读']), js_str(yy), zd, cc))

def main():
    s = open(G, encoding='utf8').read()
    orig = s
    for d in TEXTS:
        e = entry_js(d)
        tag = "{title:'%s'," % d['title']
        i = s.find(tag)
        if i >= 0:
            j = s.find("\n{title:", i + 1)
            if j < 0: j = s.rindex('\n]};')
            old = s[i:j]
            new = e + (',' if old.rstrip().endswith(',') else '')
            s = s[:i] + new + s[j:]
        else:
            k = s.rindex('\n]};')
            s = s[:k] + ',\n' + e + s[k:]
    if s != orig:
        open(G, 'w', encoding='utf8').write(s)
    print('A14：9 篇', '已写入' if s != orig else '无改动')

if __name__ == '__main__':
    main()
