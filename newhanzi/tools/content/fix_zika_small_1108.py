import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import fix_zika_b_lib as L

n = 0

# 1 愁
d = L.load('愁')
for s in d['dim']['运用链']:
    w = s.get('文') or {}
    if w.get('text') == '抽刀断水水更流，举杯销愁愁更愁。':
        w['text'] = '抽刀断水水更流，举杯消愁愁更愁。'
n += L.save('愁', d)

# 2 帘
d = L.load('帘'); dm = d['dim']
JJ = ('会意字。上面是“穴”，下面是“巾”（一块布），汉典字形分析：从巾、从穴。帘就是用布、竹子等做成、'
      '挂在门窗上遮挡的东西；古时酒店门口挂的布招牌也叫“帘”（《集韵》：“帘，酒家帜。”）。'
      '繁体写作“簾”，《说文解字》释为“堂簾”，从竹、廉声，是形声字。（来源：汉典；《说文解字》）')
dm['字源']['讲解'] = JJ
for s in dm['运用链']:
    w = s.get('文') or {}
    if w.get('text') == '莫道不消魂，帘卷西风，人比黄花瘦。':
        w['text'] = '莫道不销魂，帘卷西风，人比黄花瘦。'
n += L.save('帘', d)

# 3 虏
d = L.load('虏')
for s in d['dim']['运用链']:
    if s.get('义项') == '对敌人的蔑称':
        if not s.get('句'):
            s['句'] = '李白诗里的“平胡虏”，就是平定侵扰边境的敌人，盼着亲人不用再远征。'
        if (s.get('文') or {}).get('text', '').startswith('壮志饥餐胡虏肉'):
            s['文'] = {'text': '何日平胡虏，良人罢远征。', '出处': '李白《子夜吴歌·秋歌》'}
n += L.save('虏', d)

# 4 臀
d = L.load('臀'); dm = d['dim']
if not (dm.get('六书') or {}).get('value'):
    dm['六书'] = {'value': '形声字',
                 '依据': '汉典无字形分析；汉典所引《说文》：臀本作“𡱂”，或体“𩪡”从骨、𣪫声，段注“今周易、春秋、考工記皆作臋，从肉。軍後曰殿，卽臋之假借字也”——今字从月（肉）、殿声，与讲解一致'}
    d.setdefault('src', {})['六书'] = '人工核对（汉典所引《说文》段注）'
n += L.save('臀', d)

print('改', n)
