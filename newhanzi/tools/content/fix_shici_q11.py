# shiju 重建（build_shici.py 第 8 步：字取自诗行，单首去重，每字上限 8 首，数组顺序即课内优先）
import re
def hz(s):
    return ''.join(c for c in s if '\u4e00' <= c <= '\u9fff')
idx, meta = {}, {}
for p in poems:
    meta[str(p['order'])] = {'t': p['title'], 'a': p['author']}
    seen = set()
    for ch in hz(''.join(p['lines'])):
        if ch in seen:
            continue
        seen.add(ch)
        lst = idx.setdefault(ch, [])
        if len(lst) < 8:
            lst.append(p['order'])
SJ['idx'] = idx
SJ['meta'] = meta

