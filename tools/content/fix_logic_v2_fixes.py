def load_js(path, prefix):
    s = open(path, encoding='utf-8').read()
    assert s.startswith(prefix), path
    return json.loads(s[len(prefix):].strip().rstrip(';'))


def dump_js(path, prefix, obj):
    open(path, 'w', encoding='utf-8').write(prefix + json.dumps(obj, ensure_ascii=False, separators=(',', ':')) + ';\n')


class Ctx:
    def __init__(self, yw, qz):
        self.yw, self.qz = yw, qz
        self.items = {i['name']: i for c in yw['logic']['categories'] for i in c['items']}
        self.log = {}      # fix_no -> list of (status, desc)

    def rec(self, no, status, desc):
        self.log.setdefault(no, []).append((status, desc))

    # ---------- 专题字段 ----------
    def item(self, name):
        return self.items[name]

    def set_field(self, no, name, field, new, old_hint=None):
        it = self.item(name)
        cur = it.get(field)
        if cur == new:
            return self.rec(no, 'already', f'{name}.{field}')
        if old_hint is not None and old_hint not in json.dumps(cur, ensure_ascii=False):
            return self.rec(no, 'missing', f'{name}.{field} 原值对不上')
        it[field] = new
        self.rec(no, 'applied', f'{name}.{field}')

    def list_replace(self, no, name, field, old, new):
        """列表元素整条替换：old 可以是字符串（整条相等）。新旧并存时删旧。"""
        arr = self.item(name).get(field) or []
        has_old = old in arr
        has_new = new in arr
        if has_new and not has_old:
            return self.rec(no, 'already', f'{name}.{field}[{_short(new)}]')
        if has_old and has_new:
            arr.remove(old)
            return self.rec(no, 'applied', f'{name}.{field} 删去重新出现的旧条')
        if not has_old:
            return self.rec(no, 'missing', f'{name}.{field} 找不到「{_short(old)}」')
        arr[arr.index(old)] = new
        self.rec(no, 'applied', f'{name}.{field}[{_short(new)}]')

    def list_merge(self, no, name, field, olds, new):
        """把相邻的几条（被错误拆开的）合并成一条。"""
        arr = self.item(name).get(field) or []
        if new in arr and not any(o in arr for o in olds):
            return self.rec(no, 'already', f'{name}.{field} 合并')
        if not all(o in arr for o in olds):
            return self.rec(no, 'missing', f'{name}.{field} 合并源不全')
        i = arr.index(olds[0])
        for o in olds:
            arr.remove(o)
        if new not in arr:
            arr.insert(i, new)
        self.rec(no, 'applied', f'{name}.{field} 合并为一条')

    def dict_in_list(self, no, name, field, match_key, match_vals, patch):
        """列表里的 dict（例句解析/练习）：按 match_key 的值（原或新）找到，打补丁。"""
        arr = self.item(name).get(field) or []
        hit = [d for d in arr if d.get(match_key) in match_vals]
        if not hit:
            return self.rec(no, 'missing', f'{name}.{field} 找不到 {match_key}={_short(match_vals[0])}')
        for d in hit:
            self._patch(no, d, patch, f'{name}.{field}[{_short(d.get(match_key))}]')

    def str_sub(self, no, name, field, old, new, sub=None):
        """专题字段（字符串，或 list/dict 内某个字符串）做子串替换。sub: 取到目标字符串所在容器与键的函数。"""
        it = self.item(name)
        holder, key = (it, field) if sub is None else sub(it)
        if holder is None:
            return self.rec(no, 'missing', f'{name}.{field} 定位失败')
        s = holder[key]
        if old in s:
            holder[key] = s.replace(old, new)
            return self.rec(no, 'applied', f'{name}.{field} 子串')
        if new in s:
            return self.rec(no, 'already', f'{name}.{field} 子串')
        self.rec(no, 'missing', f'{name}.{field} 子串「{_short(old)}」不在')

    # ---------- 题库 ----------
    def quiz(self, no, mode, keys, patch, point=None):
        """按题干（q / s / prompt / from+target 组合）找题：keys 里任意一个匹配即可（原题干或改后题干）。"""
        arr = self.qz['modes'][mode]
        hit = []
        for q in arr:
            k = q.get('q') or q.get('s') or q.get('prompt')
            if mode == 'rewrite':
                k = q['from'] + '|' + q['target']
            if mode == 'tag':
                k = q['tokens'][0]['t']
            if k in keys and (point is None or q.get('point') == point):
                hit.append(q)
        if not hit:
            return self.rec(no, 'missing', f'题库 {mode} 找不到「{_short(keys[0])}」')
        for q in hit:
            self._patch(no, q, patch, f'题库 {mode}「{_short(keys[0])}」')

    def _patch(self, no, obj, patch, desc):
        changed = False
        for k, v in patch.items():
            if callable(v):
                nv = v(obj)
                if nv is None:
                    continue
                v = nv
            if obj.get(k) != v:
                obj[k] = v
                changed = True
        self.rec(no, 'applied' if changed else 'already', desc)


def _short(s, n=24):
    s = s if isinstance(s, str) else json.dumps(s, ensure_ascii=False)
    return s if len(s) <= n else s[:n] + '…'


def judge_mis(a, wu, zf):
    """判断题误解标注：按口径填选项。"""
    return [{'选项': 'A', '选项文本': '错误', '误解': wu, '正反例': zf}] if a else \
           [{'选项': 'B', '选项文本': '正确', '误解': wu, '正反例': zf}]


def sub_opt(old, new):
    """返回一个 patch 函数：把 opts 里 old 换成 new（已换过则不动）。"""
    def f(q):
        opts = list(q['opts'])
        if old in opts:
            opts[opts.index(old)] = new
        return opts
    return f


def sub_mis(letter, **kv):
    """返回 patch 函数：改 误解标注 中某个选项的字段。"""
    def f(q):
        ms = json.loads(json.dumps(q.get('误解标注') or [], ensure_ascii=False))
        for m in ms:
            if m.get('选项') == letter:
                m.update(kv)
        return ms
    return f


def chain(*fns):
    """多个对同一字段的 patch 函数串起来。"""
    def f(q):
        tmp = dict(q)
        out = None
        for fn in fns:
            out = fn(tmp)
            tmp['误解标注'] = out
        return out
    return f


