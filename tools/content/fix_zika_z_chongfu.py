def pick(yl, idx, w):
    def one(f):
        c = [i for i in idx if f(yl[i])]
        return c[0] if len(c) == 1 else None
    for f in (lambda s: w in (s.get('句') or ''),
              lambda s: w in ((s.get('文') or {}).get('text') or '')):
        r = one(f)
        if r is not None: return r
    zi = ZI[0]
    ov = [len(set(w.replace(zi, '')) & set(yl[i].get('义项') or '')) for i in idx]
    if max(ov) > 0 and ov.count(max(ov)) == 1: return idx[ov.index(max(ov))]
    need = [i for i in idx if len(yl[i]['词']) == 1]
    if len(need) == 1: return need[0]
    return min(idx, key=lambda i: (len(yl[i]['词']), i))

def fix_card(d, log=None):
    yl = d['dim'].get('运用链') or []
    cnt = collections.Counter(w for s in yl for w in (s.get('词') or []))
    ch = 0
    for w, n in cnt.items():
        if n < 2: continue
        idx = [i for i, s in enumerate(yl) if w in (s.get('词') or [])]
        if len(idx) < 2:   # 同一义项内重复
            s = yl[idx[0]]; seen = []
            for x in s['词']:
                if x not in seen: seen.append(x)
            s['词'] = seen; ch += 1; continue
        ZI[0] = d['zi']
        keep = KEEP.get((d['zi'], w))
        keep = next((i for i in idx if keep and keep in yl[i]['义项']), None) if keep else None
        if keep is None: keep = pick(yl, idx, w)
        for i in idx:
            if i != keep: yl[i]['词'] = [x for x in yl[i]['词'] if x != w]; ch += 1
        if log is not None: log.append((d['zi'], w, yl[keep]['义项'], [yl[i]['义项'] for i in idx if i != keep]))
    return ch

