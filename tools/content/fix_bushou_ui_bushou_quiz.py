"""F6 部首题库修复（审查 bushou_ui.md 第 15 节：解析和事实/答案矛盾 13 题）。按题干定位，可重复运行。
出处：《说文》明「从月从囧」（会意，今作日+月）、森「木多皃。从林从木」、相「省视也。从目从木」、
休「息止也。从人依木」、灋「平之如水，从水；廌所以触不直者去之，从去」（会意）、迷「从辵米声」、服「从舟𠬝声」。"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import fix_bushou_ui_lib as L
P = 'newhanzi/quiz/data_bushou.js'
D, F = L.load(P); M = D['modes']
log = []
def find(mode, key, val):
    for i, q in enumerate(M[mode]):
        if q.get(key) == val: return i, q
    return None, None
def setq(mode, key, val, **kw):
    i, q = find(mode, key, val)
    if q is None: return
    q.update(kw); log.append('%s[%d] %s' % (mode, i, val))

# blank：会意字被套成形声模板
setq('blank', 's', "哪个字加上偏旁'日'能变成'明'？",
     exp="'月'加上'日'就是'明'。明是会意字：太阳和月亮合在一起，表示明亮；月不是声旁。")
setq('blank', 's', "哪个字加上偏旁'木'能变成'森'？",
     exp="'林'加上'木'就是'森'。森是会意字：三个木表示树木很多（《说文》：木多貌）；林不是声旁。")
setq('blank', 's', "哪个字加上偏旁'亻'能变成'休'？",
     exp="'木'加上'亻'就是'休'。休是会意字：人靠着树歇息；木不是声旁。")
setq('blank', 's', "哪个字加上偏旁'木'能变成'相'？",
     exp="'目'加上'木'就是'相'。相是会意字：用眼睛看树木，本义是仔细察看（《说文》：省视也）；目不是声旁。")
setq('blank', 's', "哪个字加上偏旁'氵'能变成'法'？",
     exp="'去'加上'氵'就是'法'。法不是形声字，去（qù）和法（fǎ）读音也不近；《说文》说法要像水一样平，所以有氵。")
# 迷 = 辶 + 米，原题写成氵
setq('blank', 's', "哪个字加上偏旁'氵'能变成'迷'？", s="哪个字加上偏旁'辶'能变成'迷'？",
     exp="'米'加上'辶'就是'迷'。形声字小窍门：一边表义（辶和走路有关，走错路就是迷路），一边表声（米和迷读音相近）。")
# rewrite：题面操作拼不出答案
setq('rewrite', 'from', "'历'（厂+力）", **{'from': "'历'", 'target': "给'历'加上'氵'",
     'exp': "历整个当声旁：氵+历=沥（沥青）。"})
setq('rewrite', 'from', "'反'（厂+又）", **{'from': "'反'", 'target': "给'反'加上'饣'",
     'exp': "反整个当声旁：饣+反=饭（米饭）。"})
# judge
setq('judge', 'q', "'服'是'月'部的字。",
     exp="对。查字典'服'归月部；不过这个'月'在古文字里是'舟'（《说文》：服，从舟），不是肉月。")
setq('judge', 'q', "'心'在字底作偏旁时写作'忄'。",
     exp="错。忄只在字的左边（如情）；在字底大多仍写'心'（如想、念、急），少数字写作'⺗'（如恭、慕）。")
setq('judge', 'q', "'拿'是'手'部的字。", q="'拿'字下面的'手'不写成提手旁'扌'。", a=True,
     exp="对。拿=合+手，手在字底保持'手'的样子；提手旁'扌'只出现在字的左边（如打、拍）。")
setq('judge', 'q', "'全'是'亻'部的字。", q="'全'字上面是人字头，不是单人旁'亻'。", a=True,
     exp="对。全=人+王，上面是人字头；单人旁'亻'只出现在字的左边（如你、他）。")
# choice：心字底以偏概全
setq('choice', 'q', "'心'在字底作偏旁时写作？", q="'恭'字下面的'⺗'是哪个字的变形？",
     opts=['心', '小', '水', '火'], a=0,
     exp="'⺗'是'心'在字底的一种写法，只出现在恭、慕等少数字里；大多数心字底照写'心'（想、思、念、急）。",
     **{'误解标注': [
         {'选项': 'B', '选项文本': '小', '误解': "'⺗'被看成'小'，形近混淆", '正反例': ['恭=共+⺗（心）√', '恭=共+小✗']},
         {'选项': 'C', '选项文本': '水', '误解': "把'⺗'和水在字底的写法'氺'（如泰）弄混", '正反例': ['恭的⺗是心√', '泰的氺是水√']},
         {'选项': 'D', '选项文本': '火', '误解': "看到下面有点，就以为是火的变形'灬'", '正反例': ['热=执+灬（火）√', '恭=共+灬✗']}]})
L.save(P, D, F)
print(len(log), *log, sep='\n')
