def ls_set(dm, value=..., sheng=..., xing=..., yiju=...):
    l6 = dm.setdefault('六书', {})
    for k, v in (('value', value), ('声旁', sheng), ('形旁', xing), ('依据', yiju)):
        if v is ...: continue
        if v is None: l6.pop(k, None)
        else: l6[k] = v


def jj_replace(dm, old, new):
    t = dm['字源'].get('讲解') or ''
    if old in t: dm['字源']['讲解'] = t.replace(old, new, 1)


