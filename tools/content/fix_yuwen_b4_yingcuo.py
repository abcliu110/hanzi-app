def _lab(w):
    if w in XZ: return '性质形容词'
    if w in ZT: return '状态形容词'
    return dict(NON)[w]


def xingrongci():
    """形容词库：「形状形容词」不是通行分类（黄廖只分性质形容词、状态形容词；大小方圆是性质形容词）。
    原「形状形容词」子类并入性质形容词；整库按选项顺序写解析；状态形容词句子改通顺（原「墙壁雪白的」）、
    「雪花雪白雪白的」找形容词答「雪白」等错改掉。"""
    name, d, fn = load_bank('xingrongci')
    cnt = {}
    out = []
    for i, q in enumerate(d['questions']):
        cls = '性质形容词' if q['类'] in ('性质形容词', '形状形容词') else '状态形容词'
        t = q['q']
        typ = 'A' if t.startswith('下面哪个词是') else 'B' if '句子中' in t else 'C' if t.startswith('选') else 'D'
        k = cnt.get((cls, typ), 0); cnt[(cls, typ)] = k + 1
        rng = random.Random('xrc|%d' % i)
        mine, other = (XZ, ZT) if cls == '性质形容词' else (ZT, XZ)
        if typ == 'A':
            ans = mine[k % len(mine)]
            nn = NON[(k * 5) % len(NON)], NON[(k * 5 + 7) % len(NON)]
            opts = [ans, other[(k * 3) % len(other)], nn[0][0], nn[1][0]]; rng.shuffle(opts)
            exp = '「%s」是%s。' % (ans, cls)
            exp += '其他三个：' + '，'.join('「%s」是%s' % (o, _lab(o)) for o in opts if o != ans) + '。'
            exp += '性质形容词能加「很」（很高、很美丽）；状态形容词本身带着程度，不加「很」（不说很雪白）。'
            nq = {'q': '下面哪个词是%s？' % cls, 'options': opts, 'answer': opts.index(ans), '解析': exp}
        elif typ == 'B':
            s, toks, ans = (XZ_S if cls == '性质形容词' else ZT_S)[k % 8]
            opts = toks[:]; rng.shuffle(opts)
            exp = '「%s」说明%s怎么样，是%s。' % (ans, toks[0] if toks[0] not in ('这条', '这棵', '这个') else toks[1], cls)
            nq = {'q': '%s 句子中的%s是？' % (s, cls), 'options': opts, 'answer': opts.index(ans), '解析': exp}
        elif typ == 'C':
            stem, ans, wrong = (FILL_XZ if cls == '性质形容词' else FILL_ZT)[k % 6]
            nn = NON[(k * 5 + 1) % 8], NON[(k * 5 + 4) % 8]
            if wrong is None: wrong = NON[8 + k % 4][0]
            opts = [ans, wrong, nn[0][0], nn[1][0]]; rng.shuffle(opts)
            if cls == '性质形容词':
                exp = '空前有「很」，要填能受「很」修饰的性质形容词「%s」：%s「%s」是状态形容词，前面不能加「很」；「%s」「%s」不是形容词。' % (
                    ans, stem.replace('___', ans), wrong, nn[0][0], nn[1][0])
            else:
                exp = '「%s」是状态形容词，说明事物的样子：%s其他三个都不是形容词：「%s」是%s，「%s」是%s，「%s」是%s。' % (
                    ans, stem.replace('___', ans), wrong, _lab(wrong), nn[0][0], nn[0][1], nn[1][0], nn[1][1])
            nq = {'q': '选%s填入___处：%s' % (cls, stem), 'options': opts, 'answer': opts.index(ans), '解析': exp}
        else:
            tr, fl = ST[cls]
            true = tr[k % 3]
            f = fl[:]; random.Random('xrcD|%d' % k).shuffle(f)
            opts = [true] + f[:3]; rng.shuffle(opts)
            exp = true + ' 其他三项都不对：' + '；'.join(x.rstrip('。') for x in f[:3]) + '。'
            nq = {'q': '下面说法正确的是？', 'options': opts, 'answer': opts.index(true), '解析': exp}
        nq['类'] = cls
        out.append(nq)
    n = sum(1 for a, b in zip(d['questions'], out) if a != b)
    d['questions'] = out
    save_bank(fn, name, d)
    # 讲解 data.js
    dd, tail = load_data()
    it = item(dd, '形容词', 'grammar')
    it['例子'] = [x for x in it['例子'] if x not in ('红、方（形状）', '迅速、雪白（状态）')]
    it['例子'][:0] = ['红、方、大、圆（性质形容词，能说“很红”“很圆”）', '雪白、暖洋洋（状态形容词，不说“很雪白”）']
    it['口诀'] = '能加“很”的是性质，带着程度的是状态'
    it['讲解'] = '表示人或事物的形状、性质、状态的词'
    it['深讲'] = ('形容词表示人或事物的形状、性质和状态，按语法特点分两类：性质形容词（善良、勇敢、大、圆）能受“很、不”修饰；'
                '状态形容词（雪白、暖洋洋、整整齐齐）本身带着程度，一般不再受“很”修饰。表示形状的“方、圆、大、小”也是性质形容词。'
                '形容词后面一般不能直接带宾语；作定语时常带“的”，作谓语时直接说明主语怎么样，作补语时说明动作的结果或样子。')
    it['分类'] = [c for c in it['分类'] if c['类'] != '形状形容词']
    for c in it['分类']:
        if c['类'] == '性质形容词':
            c.update({'说明': '表示人或事物的性质（也包括形状、大小），大多能受“很”“不”修饰。', '代表': '善良、勇敢、大、圆',
                      '例子': ['她是一个勇敢的孩子。', '桌子是方的。']})
        if c['类'] == '状态形容词':
            c['说明'] = '表示事物的样子，本身带着程度，常是叠音或重叠的形式，一般不受“很”修饰。'
    it['怎么认'] = ['前面能不能加“很”？“很红、很勇敢”通顺的，多半是性质形容词。',
                  '后面能不能直接带宾语？形容词一般不能：不说“红了苹果”“美丽花园”当动宾讲。',
                  '能不能回答“怎么样”？能回答主语“怎么样”的，多半是形容词；“雪白、亮晶晶”不加“很”也能回答，是状态形容词。']
    save_data(dd, tail)
    return n


